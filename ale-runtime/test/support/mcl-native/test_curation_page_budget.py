"""Actual pinned Hermes spill policy against real Brain pages; no model or cloud."""
from __future__ import annotations

import copy
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[3]
SDK = Path(os.environ.get('MCL_HERMES_SOURCE', '/opt/hermes'))


def generate_pages(destination):
    """Run only in the Brain-capable environment; emit exact wire strings for SDK tests."""
    sys.path.insert(0, str(ROOT / 'brain'))
    from saleads_brain.curation import CurationQueue
    from saleads_brain.graph import InMemoryStore
    from saleads_brain.knowledge import MemoryContext, MemoryWriter
    from saleads_brain.ledger import Ledger

    fixture = json.loads((ROOT / 'contracts/continuous-loop/v1/fixtures.json').read_text())['source-event']
    context = MemoryContext(fixture['owner_id'], fixture['business_id'])
    cases = {}
    for name, unicode_source in (('large', False), ('unicode', True)):
        with tempfile.TemporaryDirectory() as directory:
            memory = MemoryWriter(Ledger(Path(directory) / 'ledger.db'), InMemoryStore())
            queue = CurationQueue(memory.ledger, memory)
            for index in range(1 if unicode_source else 18):
                source = copy.deepcopy(fixture)
                text = ('Investigación 🙂\n\t\x00' * 1500)[:24000] if unicode_source else f'Evidence {index}: ' + 'Research source. ' * 720
                source.update(event_id=f'source-{index}', source_id=f'source-{index}',
                              source_kind='api_observation', author={'kind': 'api', 'id': 'sdk-fixture'},
                              purpose='business_work', content=text, content_sha256=hashlib.sha256(text.encode()).hexdigest())
                if unicode_source:
                    source['refs'] = [f'https://example.test/{number}/' + 'r' * 2000 for number in range(30)]
                memory.register_source(context, source)
            batch = queue.create(context)
            queue.bind_native(context, batch['batch_id'], 'task-curator-fixture', 'run-curator-fixture')
            document = json.dumps(queue.read(context, batch['batch_id']), ensure_ascii=False,
                                  sort_keys=True, separators=(',', ':'))
            pages, cursor = [], None
            while True:
                page = queue.read_page(context, batch['batch_id'], cursor)
                pages.append({'wire': json.dumps(page, ensure_ascii=False),
                              'ascii_wire': json.dumps(page, ensure_ascii=True)})
                cursor = page['next_cursor']
                if cursor is None:
                    break
                if len(pages) >= 1000:
                    raise AssertionError('Bounded fixture cursor did not terminate')
            cases[name] = {'canonical_document': document, 'pages': pages,
                           'payload_sha256': hashlib.sha256(document.encode()).hexdigest()}
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps({'schema_version': 'curation-page-sdk-fixture/1', 'cases': cases},
                                    ensure_ascii=False) + '\n')
    destination.chmod(0o444)  # Synthetic CI artifact read by the SDK's UID10000.
    print(json.dumps({'generated_pages': {name: len(case['pages']) for name, case in cases.items()}}))


@unittest.skipUnless(SDK.is_dir(), 'Requires the actual pinned Hermes image')
class NativeCurationPageBudget(unittest.TestCase):
    def check_document(self, *, unicode_source=False):
        # Hermes must consume the Brain-generated bytes without importing Brain
        # or acquiring any of its dependencies (including PyYAML).
        sys.path.insert(0, str(SDK))
        from tools.budget_config import budget_for_context_window
        from tools.tool_result_storage import enforce_turn_budget, maybe_persist_tool_result

        artifact = json.loads(Path(os.environ['MCL_CURATION_PAGE_FIXTURE']).read_text())
        self.assertEqual(artifact['schema_version'], 'curation-page-sdk-fixture/1')
        case = artifact['cases']['unicode' if unicode_source else 'large']
        self.assertTrue(case['pages'])
        budget = budget_for_context_window(1)  # Exercise the official 8000-character floor.
        self.assertEqual(budget.default_result_size, 8000)
        fragments, next_cursor = [], None
        with patch('tools.tool_result_storage._write_to_spillover', side_effect=AssertionError('Page must stay inline')):
            for count, emitted in enumerate(case['pages']):
                page = json.loads(emitted['wire'])
                self.assertEqual(json.loads(emitted['ascii_wire']), page)
                self.assertEqual(page['offset'], sum(map(len, fragments)))
                self.assertEqual(page['payload_sha256'], case['payload_sha256'])
                if count:
                    self.assertEqual(next_cursor, f"curation-page/1:{page['payload_sha256']}:{page['offset']}")
                for rendered in (emitted['wire'], emitted['ascii_wire']):
                    # Pass the stored wire strings unchanged into the actual SDK.
                    self.assertLessEqual(len(rendered), 6000)
                    self.assertEqual(maybe_persist_tool_result(rendered, 'saleads_curation_batch', f'page-{count}', config=budget), rendered)
                    messages = [{'tool_call_id': f'page-{count}', 'content': rendered}]
                    self.assertEqual(enforce_turn_budget(messages, config=budget)[0]['content'], rendered)
                fragments.append(page['fragment'])
                next_cursor = page['next_cursor']
        document = ''.join(fragments)
        self.assertIsNone(next_cursor)
        self.assertEqual(hashlib.sha256(document.encode()).hexdigest(), case['payload_sha256'])
        self.assertEqual(document, case['canonical_document'])
        if not unicode_source:
            self.assertGreater(len(document), 204908)
            self.assertLess(len(case['pages']), 60)
        self.assertFalse(any(name == 'saleads_brain' or name.startswith('saleads_brain.') for name in sys.modules))

    def test_large_batch_stays_inline_under_the_actual_sdk_minimum_budget(self):
        self.check_document()

    def test_unicode_controls_and_single_source_large_refs_stay_inline(self):
        self.check_document(unicode_source=True)


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--emit-pages':
        generate_pages(sys.argv[2])
    else:
        unittest.main()
